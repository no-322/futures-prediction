"""Generate the ASCII module diagram + inventory, and check MODULES.md completeness.

Deterministic parts of the docs are machine-generated from the source AST:
  * ``docs/notes/module_diagram.md`` — an ASCII import graph (who imports whom, within
    ``src``) plus a per-module function inventory. Fully regenerated on every run.
  * ``--check`` — verify that every public ``src`` function has an entry in
    ``docs/MODULES.md`` (name present). The author-written pseudocode/logic block per
    function cannot be machine-generated; this check enforces that MODULES.md at least
    lists every function, so nothing is silently undocumented.

Run with::

    python -m src.gen_module_docs            # (re)write docs/notes/module_diagram.md
    python -m src.gen_module_docs --check     # verify MODULES.md lists every function
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

_SRC = Path("src")
_DIAGRAM = Path("docs/notes/module_diagram.md")
_MODULES = Path("docs/MODULES.md")


def _module_name(path: Path, root: Path) -> str:
    """Dotted module name for a src file, e.g. src/models/rf.py → src.models.rf."""
    rel = path.with_suffix("").relative_to(root.parent)
    return ".".join(rel.parts)


def build_inventory(src: Path = _SRC) -> dict[str, list[str]]:
    """Map each ``src`` module → its list of top-level function names (sorted).

    Args:
        src: Root of the source tree.

    Returns:
        Dict of dotted-module-name → list of def names (public + private), in file order.
    """
    inv: dict[str, list[str]] = {}
    for path in sorted(src.rglob("*.py")):
        if "__pycache__" in path.parts or path.name == "__init__.py":
            continue
        tree = ast.parse(path.read_text())
        funcs = [n.name for n in tree.body if isinstance(n, ast.FunctionDef)]
        inv[_module_name(path, src)] = funcs
    return inv


def build_import_graph(src: Path = _SRC) -> dict[str, list[str]]:
    """Map each ``src`` module → the ``src`` modules it imports (sorted, deduped).

    Only intra-``src`` edges are recorded (external deps like numpy are ignored).
    """
    modules = set(build_inventory(src))
    graph: dict[str, list[str]] = {}
    for path in sorted(src.rglob("*.py")):
        if "__pycache__" in path.parts or path.name == "__init__.py":
            continue
        me = _module_name(path, src)
        deps: set[str] = set()
        tree = ast.parse(path.read_text())
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module \
                    and node.module.startswith("src"):
                deps.add(node.module)
            elif isinstance(node, ast.Import):
                for a in node.names:
                    if a.name.startswith("src"):
                        deps.add(a.name)
        # keep only edges to real modules (drop packages like ``src.models``), not self
        graph[me] = sorted(d for d in deps if d in modules and d != me)
    return graph


def render_module_diagram(inv: dict[str, list[str]], graph: dict[str, list[str]]) -> str:
    """Render the ASCII import graph + module/function inventory as markdown."""
    lines = [
        "# Module Diagram & Inventory",
        "",
        "_Auto-generated by `src/gen_module_docs.py` — do not edit by hand._",
        "",
        "## Import graph (intra-`src` edges)",
        "",
        "```",
    ]
    for mod in sorted(graph):
        deps = graph[mod]
        if deps:
            lines.append(f"{mod}")
            for d in deps:
                lines.append(f"    └─▶ {d}")
        else:
            lines.append(f"{mod}   (no intra-src imports)")
    lines += ["```", "", "## Inventory", "",
              "| Module | Functions | Count |",
              "|--------|-----------|-------|"]
    for mod in sorted(inv):
        funcs = inv[mod]
        shown = ", ".join(f"`{f}`" for f in funcs) if funcs else "—"
        lines.append(f"| `{mod}` | {shown} | {len(funcs)} |")
    lines.append("")
    return "\n".join(lines)


def generate(diagram_path: Path = _DIAGRAM) -> None:
    """Regenerate the module diagram + inventory file."""
    inv = build_inventory(_SRC)
    graph = build_import_graph(_SRC)
    diagram_path.parent.mkdir(parents=True, exist_ok=True)
    diagram_path.write_text(render_module_diagram(inv, graph))
    print(f"module diagram → {diagram_path}")


def check_modules_md(modules_path: Path = _MODULES) -> list[str]:
    """Return ``module.func`` names that have no entry (by name) in MODULES.md.

    Private helpers (leading underscore) are exempt from the requirement.
    """
    if not modules_path.exists():
        return ["<docs/MODULES.md missing>"]
    text = modules_path.read_text()
    missing: list[str] = []
    for mod, funcs in build_inventory(_SRC).items():
        for fn in funcs:
            if fn.startswith("_"):
                continue
            if f"`{fn}`" not in text and f"| {fn} " not in text:
                missing.append(f"{mod}.{fn}")
    return missing


def main() -> None:
    parser = argparse.ArgumentParser(description="Module diagram generator / doc check.")
    parser.add_argument("--check", action="store_true",
                        help="Verify MODULES.md lists every public src function.")
    args = parser.parse_args()
    if args.check:
        missing = check_modules_md()
        if missing:
            print("MODULES.md is missing entries for:", file=sys.stderr)
            for m in missing:
                print(f"  - {m}", file=sys.stderr)
            sys.exit(2)
        print("MODULES.md lists every public src function.")
    else:
        generate()


if __name__ == "__main__":
    main()
